"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

import numpy as np
import matplotlib.pyplot as plt

# Beam Parameters (Example: Simply supported beam with uniform load)
L = 10.0      # Length of beam (m)
w = 20.0      # Uniformly distributed load (kN/m)

# Coordinates along the beam
x_beam = np.linspace(0, L, 1000)

# Shear force V(x) = w * (L/2 - x)
V = w * (L / 2.0 - x_beam)

# Plotting Shear Diagram
plt.figure(figsize=(8, 4))
plt.plot(x_beam, V, 'r-', linewidth=2, label='Shear Force (V)')
plt.fill_between(x_beam, V, color='red', alpha=0.15)
plt.axhline(0, color='black', linewidth=1)
plt.title('Shear Force Diagram')
plt.xlabel('Length along beam (m)')
plt.ylabel('Shear Force (kN)')
plt.grid(True, linestyle='--')
plt.legend()
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Moment M(x) = (w * x / 2) * (L - x)
M = (w * x_beam / 2.0) * (L - x_beam)

# Plotting Moment Diagram
plt.figure(figsize=(8, 4))
plt.plot(x_beam, M, 'b-', linewidth=2, label='Bending Moment (M)')
plt.fill_between(x_beam, M, color='blue', alpha=0.15)
plt.axhline(0, color='black', linewidth=1)
plt.title('Bending Moment Diagram')
plt.xlabel('Length along beam (m)')
plt.ylabel('Bending Moment (kNm)')
plt.grid(True, linestyle='--')
plt.legend()
plt.show()

